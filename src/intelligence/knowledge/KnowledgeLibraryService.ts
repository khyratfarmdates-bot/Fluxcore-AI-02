class KnowledgeLibraryService {
  // تفعيل مكتبة معينة لبراند معين
  toggleLibrary(brandId: string, libraryId: string, enabled: boolean): void {
    try {
      const key = `fluxcore_library_status_${brandId}`;
      const saved = localStorage.getItem(key);
      const statusMap = saved ? JSON.parse(saved) : {};
      statusMap[libraryId] = enabled;
      localStorage.setItem(key, JSON.stringify(statusMap));
    } catch (e) {
      console.error("Failed to toggle library:", e);
    }
  }

  // معرفة هل المكتبة مفعلة للبراند
  isLibraryEnabled(brandId: string, libraryId: string): boolean {
    try {
      const key = `fluxcore_library_status_${brandId}`;
      const saved = localStorage.getItem(key);
      if (!saved) {
        // تفعيل كل المكتبات افتراضياً لأول مرة لتسهيل الاستخدام
        return true;
      }
      const statusMap = JSON.parse(saved);
      return statusMap[libraryId] !== false; // true by default if not set to false
    } catch (e) {
      return true;
    }
  }

  // الحصول على كل المستندات المخصصة للبراند
  getCustomDocuments(brandId: string): CustomDocument[] {
    try {
      const key = `fluxcore_custom_docs_${brandId}`;
      const saved = localStorage.getItem(key);
      return saved ? JSON.parse(saved) : [];
    } catch (e) {
      return [];
    }
  }

  // إضافة مستند مخصص
  addCustomDocument(brandId: string, title: string, content: string): CustomDocument[] {
    try {
      const key = `fluxcore_custom_docs_${brandId}`;
      const docs = this.getCustomDocuments(brandId);
      const newDoc: CustomDocument = {
        id: 'doc-' + Date.now() + '-' + Math.floor(Math.random() * 1000),
        title,
        content,
        createdAt: Date.now()
      };
      const updated = [newDoc, ...docs];
      localStorage.setItem(key, JSON.stringify(updated));
      return updated;
    } catch (e) {
      console.error("Failed to add custom doc:", e);
      return [];
    }
  }

  // حذف مستند مخصص
  deleteCustomDocument(brandId: string, docId: string): CustomDocument[] {
    try {
      const key = `fluxcore_custom_docs_${brandId}`;
      const docs = this.getCustomDocuments(brandId);
      const updated = docs.filter(d => d.id !== docId);
      localStorage.setItem(key, JSON.stringify(updated));
      return updated;
    } catch (e) {
      console.error("Failed to delete custom doc:", e);
      return [];
    }
  }

  // تجميع كل السياق المعرفي المفعل للعلامة التجارية لتقديمه للموديل
  getActiveKnowledgeContext(brandId: string): string {
    let contextParts: string[] = [];

    // 1. المكتبات الجاهزة المفعلة
    BUILT_IN_LIBRARIES.forEach(lib => {
      if (this.isLibraryEnabled(brandId, lib.id)) {
        contextParts.push(lib.content);
      }
    });

    // 2. المستندات المخصصة
    const customDocs = this.getCustomDocuments(brandId);
    customDocs.forEach(doc => {
      contextParts.push(`[مستند معرفي مخصص: ${doc.title}]\n${doc.content}`);
    });

    return contextParts.join("\n\n---\n\n");
  }
}

export const knowledgeLibraryService = new KnowledgeLibraryService();
